"""Writes App/Connectors/Generated/ConnectorTools.generated.swift from the connector manifests.

The Apple model needs a typed @Generable argument struct per tool, so one small struct is generated for each manifest tool.
Everything else about a tool (description, request, parsing, approval card) is read from the manifest at run time.

    python scripts/gen_connector_tools.py          write the file
    python scripts/gen_connector_tools.py --check  exit 1 when the committed file is stale
"""
import os, re, sys, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..')) + '/'
OUT = ROOT + 'App/Connectors/Generated/ConnectorTools.generated.swift'
LIT = r'"((?:[^"\\]|\\.)*)"'
KEYWORDS = {'class', 'default', 'func', 'let', 'var', 'in', 'is', 'as', 'for', 'if', 'else', 'switch', 'case', 'return', 'repeat', 'while',
            'where', 'self', 'super', 'init', 'true', 'false', 'nil', 'protocol', 'struct', 'enum', 'extension', 'import', 'operator', 'static',
            'subscript', 'typealias', 'do', 'try', 'catch', 'throw', 'throws', 'rethrows', 'break', 'continue', 'defer', 'guard', 'inout', 'internal',
            'fileprivate', 'private', 'public', 'open', 'Type', 'Any', 'description', 'unused'}


def unesc(s):
    return re.sub(r'\\(.)', r'\1', s)


def swift_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def bracket_body(blk, key):
    i = blk.find(key + ': [')
    if i < 0:
        return ''
    body = blk[i + len(key) + 2:]
    d = 0; instr = False; esc = False
    for n, ch in enumerate(body):
        if instr:
            if esc: esc = False
            elif ch == '\\': esc = True
            elif ch == '"': instr = False
        else:
            if ch == '"': instr = True
            elif ch == '[': d += 1
            elif ch == ']':
                d -= 1
                if d == 0: return body[:n + 1]
    return ''


def tools():
    out = []
    for f in sorted(glob.glob(ROOT + 'Packages/ToolKit/Sources/Connectors/*Manifest.swift')):
        if f.endswith('ConnectorManifest.swift'): continue
        s = open(f, encoding='utf-8').read()
        for blk in s.split('ConnectorToolSpec(')[1:]:
            name = re.search(r'name:\s*' + LIT, blk).group(1)
            args = []
            for m in re.finditer(r'ConnectorArg\(\s*"(\w+)",\s*guide:\s*' + LIT, bracket_body(blk, 'arguments')):
                args.append((m.group(1), unesc(m.group(2))))
            out.append((name, args))
    return out


def generate():
    lines = ['// Generated by scripts/gen_connector_tools.py from the connector manifests. Do not edit by hand.',
             'import Foundation', 'import FoundationModels', 'import PolicyEngine', 'import ToolKit', '']
    names = []
    for name, args in tools():
        for a, _ in args:
            if a in KEYWORDS: raise SystemExit('argument name %s of %s is a Swift keyword' % (a, name))
        struct = 'ConnTool_' + name
        names.append((name, struct))
        lines += ['struct %s: Tool {' % struct,
                  '    let name = %s' % swift_str(name),
                  '    var description: String { ConnectorRegistry.owner(ofTool: %s)?.tool.description ?? "" }' % swift_str(name),
                  '    let gate: PolicyGate; let ctx: TaskContext; let reporter: any ToolReporter', '',
                  '    @Generable struct Arguments {']
        if args:
            for a, g in args:
                lines.append('        @Guide(description: %s) var %s: String' % (swift_str(g), a))
        else:
            lines.append('        @Guide(description: "Always an empty string.") var unused: String')
        lines += ['    }', '', '    func call(arguments a: Arguments) async throws -> String {']
        pairs = ', '.join('%s: a.%s' % (swift_str(x), x) for x, _ in args) if args else ''
        lines += ['        await runManifestTool(gate, ctx, reporter, name: name, json: [%s])' % (pairs if args else ':'), '    }', '}', '']
    lines += ['/// Every manifest tool as an Apple-model tool, keyed by tool name.',
              'func makeConnectorTools(gate: PolicyGate, ctx: TaskContext, reporter: any ToolReporter) -> [String: any Tool] {',
              '    [']
    for name, struct in names:
        lines.append('        %s: %s(gate: gate, ctx: ctx, reporter: reporter),' % (swift_str(name), struct))
    lines += ['    ]', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        have = open(OUT, encoding='utf-8', newline='').read() if os.path.exists(OUT) else ''
        if have != text:
            print('ConnectorTools.generated.swift is stale: run python scripts/gen_connector_tools.py')
            sys.exit(1)
        print('generated file is current')
    else:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, 'w', encoding='utf-8', newline='').write(text)
        print('wrote', OUT.replace(ROOT, ''), '-', text.count('struct ConnTool_'), 'tools')
